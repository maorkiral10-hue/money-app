// גרסאות 1–2 היו דף בדיקת ההיתכנות. 3: גיבוי ועותקי בטיחות. 4: שלב 2 (הזנה ויתרה).
// 5: הזנה שלב אחר שלב, פירוט ומסך צפי מאחורי כפתורים. 6: שלב 3 (קבועות, הזנה מהירה).
// 7: קבועה באשראי יורדת ביום החיוב של הכרטיס, בלי לשאול תאריך. 8: מסגרות אשראי.
// 9: בחירה + "המשך" בהזנה, תיקון כפתור חזרה, תפריט הגדרות מסודר.
// 10: "כל שנה" בקבועות, מחיקה בהחלקה שמאלה.
// 11: הזנה מהירה מקבלת מהקיצור גם סכום, קטגוריה ואמצעי תשלום.
// 12: פתיחה ישר על הזנה, "הוסף מהקיצור" (העתקה-הדבקה), אישור "נשמר" עם ביטול.
// 13: חזרה לאפליקציה אחרי 10 שניות (לא באמצע הקלדה) פותחת הזנה חדשה, בשביל הקיצור.
// 14: הקיצור יכול לשלוח "הוצאה" / "הכנסה" בעברית.
// 15: שלב 4 — סרגל תפריט תחתון עם החלקה, מסך "תמונת מצב".
// 16: פירוט "עד סוף החודש", חיוב האשראי שאחרי סוף החודש, כרטיסים בתמונת מצב, יום תחילת החודש הכספי.
// 17: לשונית "החודש" עם כותרות נפתחות, לשונית "דשבורד" עם גרפים וטבלאות.
// 18: ירוק להכנסה ואדום להוצאה, צבע לכל קטגוריה, "מאיפה מגיע הכסף", "עד סוף החודש" בכותרות, "החודש הבא" עבר ל"החודש".
// 19: הוראות קבע שעוד ירדו נכללות ב"על מה הולך הכסף", אייקון הגדרות בכל לשונית.
// 20: גרירה בין הלשוניות עם אנימציה (כיוון הפוך), הגדרות צפות, "החודש" בדשבורד.
// 21: הסימון בסרגל התחתון מחליק ועוקב אחרי הגרירה; "הוסף מהקיצור" הוסר (לשלב מתקדם).
// 22: שלב 5 — לשונית תקציב (נעולה עד שאלון), תקציב כולל ולפי קטגוריה, חיסכון כסעיף נפרד או כהוצאה.
// 23: הוראות הקבע של כל החודש יורדות מהתקציב מראש (או בנפרד, לפי השאלון).
// 24: עריכה שומרת את הקשר להוראת קבע (ותיקון חד-פעמי), "סוג" לאמצעי תשלום, מספרים שסופרים כלפי מעלה.
// 25: אמצעי תשלום בהגדרות מסודרים בקבוצות לפי סוג, שורה מסוכמת לכל אחד ולחיצה לעריכה.
// 26: שדות "יום תחילת המעקב" נעלמים אחרי ההתחלה; הוראות קבע לא ברשימת התנועות אלא בשורה מסוכמת.
// 27: הבית כמו עובר ושב (חיוב כרטיס כשורה אחת, קניות אשראי בתוך הכרטיס), פירוט כרטיס בלחיצה, בועת "נשמר".
// 28: "החודש": הכנסות/הוצאות נפתחות בלחיצה, סיכום מסגרות אשראי עם מד, הוסרו תחזיות סוף החודש והחודש הבא.
// 29: אחוזים בפירוט ההוצאות; שאלה ברורה על החיוב הראשון בהוספת הוראת קבע.
// 30: "החודש" אוחד לבית (הכנסות, הוצאות, כרטיסים, "עובר ושב" בלחיצה), "נשאר" הוסר; סרגל: בית, תקציב, +, דשבורד.
// 31: בדיקת יתרה מול הבנק (השוואה, הוספת חסר או עדכון יתרה, תזכורת שקטה).
// 32: "רכישה אחרונה שנרשמה" בכל כרטיס; תזכורת בולטת לבדיקה מול הבנק (כל שבוע כברירת מחדל).
// 33: יעדי חיסכון בלשונית "יעדים": כל יעד קופה נפרדת מחוץ לכסף הנזיל, עם העברות פנימה והחוצה.
// 34: בהזנת "העברה" אפשר לבחור גם יעדי חיסכון (מאיפה ולאן).
// 35: לכל יעד קטגוריה; "הוצאה מהיעד" נרשמת כהוצאה בקטגוריה ויורדת מהיעד (גם מההזנה: "מתוך יעד חיסכון").
// 36: "נשאר" הוסר מהדשבורד (הכנסות והוצאות נופלות בחודשים שונים, אז זה לא משקף).
// 37: תפריט צד שנפתח מימין (במקום מסך ההגדרות): כותרות גדולות, כל אחת נפתחת במסך מלא; "העדפות" במסך משלהן.
// 38: בתפריט הצד: "הכסף שלי - הגדרות" (נפתח לתתי נושאים) ו"גיבוי ונתונים".
// 39: תתי הנושאים של "הכסף שלי - הגדרות" נפתחים מתחת לכותרת (שאר הכותרות נשארות).
// 40: "לוח זמנים" בתפריט הצד: אירועים עם צפי כספי (לא משפיעים על התזרים), תצוגת שנה/חודש/שבוע עם צביטה.
// 41: שעות באירועים ותצוגת יום לפי שעות; אחרי אירוע עם צפי כספי, שאלה בבית כמה זה עלה בפועל.
// 42: לוח זמנים: מאזן אירועים (צפי מול בפועל), גרירה ימינה/שמאלה בין חודשים, כפתור "אירוע חדש" למעלה.
// 43: שאלה קופצת אחרי אירוע עם צפי; "בשעות" או "כל היום" ברור באירוע; צביטה חלקה יותר ביומן.
// 44: אירועים חוזרים (כל יום/שבוע/חודש/שנה, עד תאריך); כפתור אירוע חדש אחד למעלה, מתחיל מהיום.
// 45: חזרה בימי חול או בימים שבוחרים; מחיקת יום בודד מתוך אירוע חוזר.
// 46: שינוי חד־פעמי באירוע חוזר; בלי זום של הדף (לחיצה כפולה/צביטה); לוח הזמנים מסונכרן עם הפעולות שנרשמו.
// 47: היומן בבית: שורת שבוע (צביטה/לחיצה לחודש) ומתחת רשימת היום: אירועים ופעולות יחד.
// 48: "כל החודש" (לפי החודש הכספי) במקום "עובר ושב"; קניות אשראי ביום הקנייה עם "תיגבה ב..." ושורת חיוב אפורה.
// 49: סיכום החודש בבית עובר חודש יחד עם היומן.
// 50: מד האשראי בבית לפי היום שנבחר ביומן (אחרי יום החיוב, מה שנגבה משתחרר).
// 51: ביומן: חיובי אשראי צפויים ביום החיוב והוראות קבע צפויות בתאריך שלהן; שמירה שנכשלת מציגה הודעה במקום להיתקע.
// 52: הוראת קבע באשראי מופיעה רק בתוך חיוב הכרטיס, לא שוב ביום שלה.
// 53: ביום עתידי, מד האשראי כולל גם הוראות קבע באשראי שיירדו עד אז.
// 54: הוראות קבע והכנסות קבועות נרשמות לבד (גם סכום משתנה, לפי ההערכה); בפאנל ההוצאות/ההכנסות שורת "קבועות" בראש; בלי "צפוי".
// 55: בפאנל ההוצאות שורת "חיסכון · לא נספר בהוצאות" (קופת גמל וכד׳), כשהחיסכון מוגדר בנפרד בתקציב.
// 56: הוסתרו זמנית הדשבורד, התקציב ולוח הזמנים שבתפריט (מסדרים קודם את הבית). הנתונים נשמרים.
// 57: הוראת קבע בסכום משתנה: לא נרשמת לבד; ביום שלה חלונית "כמה ירד בפועל?" שחוזרת עד שעונים (אפשר "תזכיר בעוד חצי שעה", "לא ירד החודש" + הצעה לבטל). ההערכה לא נספרת בשום חישוב.
// 58: בדיקה מול הבנק לכל מקור כסף: "כולם יחד" (עם "1 מתוך 3 נבדקו") או "לכל אחד בנפרד" עם זמן משלו; מזומן כל חודש כברירת מחדל.
// 59: בדיקה מוקדמת: "לספור מהיום" או "להישאר בקצב הרגיל"; טווח לפער מינורי (✓ / ✓✗ / ✗).
// 60: חגים, צומות, ימי זיכרון וימים לאומיים ביומן (מחושב מהלוח העברי), סימון שבתון; בבדיקה מול הבנק הערה כשפער אחרי שבת/שבתון.
// 61: הגדרת הטווח לשינוי מינורי עברה ל"העדפות".
// 62: בפירוט הכסף הנזיל: ליד כל מקור מתי נבדק לאחרונה ואיך יצא (✓ / ✓✗ / ✗).
